'use strict';
// The website is the canonical brand source. Copies keep Electron's protocol
// allowlist and the offline, single-document phone companion unchanged.
const fs = require('fs');
const path = require('path');
const root = path.join(__dirname, '..');
const tokens = fs.readFileSync(path.join(root, 'web/app/tokens.css'), 'utf8');
const check = process.argv.includes('--check');
const banner = '/* Generated by scripts/sync-design-tokens.js; do not edit. */\n';
function write(file, expected) {
  const target = path.join(root, file);
  if (fs.existsSync(target) && fs.readFileSync(target, 'utf8') === expected) return;
  if (check) { console.error(`Design tokens out of date: ${file}`); process.exitCode = 1; }
  else fs.writeFileSync(target, expected);
}
write('src/windows/assistant/ui/brand-tokens.css', banner + tokens);
const file = 'src/main-process/features/mobile-server/companion.html';
let html = fs.readFileSync(path.join(root, file), 'utf8');
const start = '<!-- shared-brand:start -->';
const end = '<!-- shared-brand:end -->';
const fonts = ['display', 'text', 'mono'].map((name) => {
  const data = fs.readFileSync(path.join(root, `src/windows/assistant/ui/fonts/red-hat-${name}.woff2`)).toString('base64');
  return `@font-face { font-family: "Red Hat ${name[0].toUpperCase() + name.slice(1)}"; font-style: normal; font-weight: 300 700; font-display: swap; src: url(data:font/woff2;base64,${data}) format("woff2"); }`;
}).join('\n');
const block = `${start}\n<style>\n${banner}${tokens}\n${fonts}\n:root { --bg: var(--ground); --hover: var(--surface-hover); --font-rh-text: "Red Hat Text"; --font-rh-display: "Red Hat Display"; --font-rh-mono: "Red Hat Mono"; --font: var(--font-sans); --r-md: 10px; --r-lg: 16px; --positive-border: var(--positive); --warning-border: var(--warning); --danger-border: var(--danger); }\n</style>\n${end}`;
if (html.includes(start)) html = html.slice(0, html.indexOf(start)) + block + html.slice(html.indexOf(end) + end.length);
else html = html.replace('</head>', block + '\n</head>');
write(file, html);
